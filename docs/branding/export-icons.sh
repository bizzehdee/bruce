#!/usr/bin/env bash
# Regenerates the launcher icon layers, the Play Store icon and feature graphic from bruce-logo.svg.
# Requires ImageMagick 7 built with librsvg (`magick -list format | grep RSVG`).
# The feature graphic uses the Montserrat font (SIL Open Font License), installed system-wide.
set -euo pipefail

cd "$(dirname "$0")/../.."
MASTER=docs/branding/bruce-logo.svg
RES=app/src/main/res
# The launcher icon has no background of its own; the Play icon must be an opaque square.
LAUNCHER_BACKGROUND="#00000000"
PLAY_BACKGROUND="#FFF3E6"
# Scratch on disk, not tmpfs.
mkdir -p build/scratch
WORK=$(mktemp -d -p build/scratch)
trap 'rm -rf "$WORK"' EXIT

# High-resolution render trimmed to the drawn content.
magick -background none -density 600 "$MASTER" -trim +repage "$WORK/content.png"

# Themed-icon layer: the coat stays opaque; the white blaze and near-black eyes, nose
# and mouth become transparent, so the features survive single-colour tinting.
magick "$WORK/content.png" -background black -alpha remove -colorspace Gray \
  -fx "u>0.88 || u<0.22 ? 0 : 1" "$WORK/feature-mask.png"
magick "$WORK/content.png" -alpha extract "$WORK/shape-mask.png"
magick "$WORK/feature-mask.png" "$WORK/shape-mask.png" -compose Multiply -composite "$WORK/mono-mask.png"
magick "$WORK/mono-mask.png" -fill white -colorize 100 "$WORK/mono-mask.png" \
  -alpha off -compose CopyOpacity -composite "$WORK/monochrome.png"

# Adaptive icon layers are 108dp square; keep the head inside the central 66dp.
for density in mdpi:1 hdpi:1.5 xhdpi:2 xxhdpi:3 xxxhdpi:4; do
  name=${density%%:*}
  scale=${density##*:}
  size=$(awk "BEGIN { print int(108 * $scale) }")
  content=$(awk "BEGIN { print int(66 * $scale) }")
  mkdir -p "$RES/mipmap-$name"
  for layer in content:ic_launcher_foreground monochrome:ic_launcher_monochrome; do
    magick "$WORK/${layer%%:*}.png" -resize "${content}x${content}" -background none \
      -gravity center -extent "${size}x${size}" -strip "PNG32:$RES/mipmap-$name/${layer##*:}.png"
  done
done

# Play Store icon: 512 x 512, full-bleed background; Play applies its own corner mask.
mkdir -p docs/store
magick "$WORK/content.png" -resize 410x410 -background "$PLAY_BACKGROUND" -gravity center \
  -extent 512x512 -alpha off -strip "PNG24:docs/store/play-icon-512.png"

# Play Store feature graphic: 1024 x 500, the head on the left and the name on the right, on the
# Play icon's background. Text stays inside the central area Play keeps clear of its own overlays.
FEATURE_TEXT="#3A2216"
FEATURE_ACCENT="#2C5176"
magick -size 1024x500 "xc:$PLAY_BACKGROUND" \
  \( "$WORK/content.png" -resize x420 \) -gravity west -geometry +90+0 -composite \
  -gravity northwest -font Montserrat-ExtraBold -pointsize 132 -fill "$FEATURE_TEXT" -annotate +500+120 "Bruce" \
  -font Montserrat-Medium -pointsize 40 -fill "$FEATURE_ACCENT" -annotate +506+285 "Your AI sidekick," \
  -annotate +506+335 "on your phone." \
  -alpha off -strip "PNG24:docs/store/feature-graphic-1024x500.png"

cat > "$RES/values/ic_launcher_background.xml" <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by docs/branding/export-icons.sh; edit LAUNCHER_BACKGROUND there. -->
<resources>
    <color name="ic_launcher_background">$LAUNCHER_BACKGROUND</color>
</resources>
XML

echo "Icons written: launcher background $LAUNCHER_BACKGROUND, Play background $PLAY_BACKGROUND"
